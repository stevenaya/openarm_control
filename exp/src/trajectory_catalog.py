#!/usr/bin/env python3
"""List every target trajectory used by the final-report experiments."""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any

import run_experiments
import study


HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
REPORT_MANIFESTS = REPO_ROOT / "exp" / "manifests"

SUITE_GENERATORS = {
    "screening": "study.screening_scenarios()",
    "parameters": "study.focused_scenarios()",
    "driver": "study.focused_scenarios()",
    "symmetry": "study.symmetry_scenarios()",
    "chest": "targeted_study.chest_scenarios()",
    "braking": (
        "targeted_study.make_joint6_limit_scenario(..., "
        "angular_speed in [2, 4, 8, 12])"
    ),
    "robustness": "targeted_study.robustness_scenarios()",
    "candidates": "study.screening_scenarios()",
    "frozen": "run_experiments.frozen_benchmarks()",
    "fast_retract_error_bound": (
        "run_experiments.accelerated_fast_retract_benchmark()"
    ),
    "singularity_video": (
        "video_trajectory_study.make_deep_start_reach(...)"
    ),
    "nullspace_sweep": (
        "run_experiments.frozen_benchmarks()[fast_retract]"
    ),
    "nullspace_validation": "study.focused_scenarios()",
}

FAMILY_BUILDERS = {
    "reach": "study.make_reach_scenario()",
    "retract": "study.make_diagonal_retract_scenario()",
    "extended_translation": "study.make_extended_circle_scenario()",
    "extended_axis": "study.make_extended_axis_scenario()",
    "extended_wrist": "study.make_wrist_flip_scenario(extended=True)",
    "normal_wrist": "study.make_wrist_flip_scenario(extended=False)",
    "chest_wrist_outward": "study.make_chest_wrist_outward_scenario()",
    "normal_workspace": "study.make_normal_lissajous_scenario()",
    "joint_braking": "targeted_study.make_joint6_limit_scenario()",
}


def _builder_for(scenario: study.Scenario) -> tuple[str, str]:
    if scenario.name == "near_chest_fast_wrist_roll":
        return (
            "frozen input",
            "load_frozen_scenario(inputs/near_chest_fast_wrist_roll.npz)",
        )
    if scenario.name == "fast_retract_elbow_branch":
        return (
            "frozen input",
            "load_frozen_scenario(inputs/fast_retract_elbow_branch.npz)",
        )
    if scenario.name == "fast_retract_elbow_branch_2x":
        return (
            "derived frozen",
            "accelerated_fast_retract_benchmark()",
        )
    if scenario.name.startswith("reach_deep_start_"):
        return (
            "procedural",
            "video_trajectory_study.make_deep_start_reach()",
        )
    return "procedural", FAMILY_BUILDERS[scenario.family]


def build_catalog() -> list[dict[str, Any]]:
    """Build one record per unique sampled target trajectory."""
    by_hash: dict[str, dict[str, Any]] = {}
    for suite in run_experiments.SUITES:
        if suite == "boundary":
            continue
        for scenario in run_experiments.suite_scenarios(suite):
            metadata = study._scenario_metadata(scenario)
            digest = str(metadata["trajectory_sha256"])
            source_kind, builder = _builder_for(scenario)
            record = by_hash.setdefault(
                digest,
                {
                    **metadata,
                    "duration_s": float(scenario.times[-1]),
                    "source_kind": source_kind,
                    "builder": builder,
                    "suites": [],
                },
            )
            if record["name"] != scenario.name:
                raise ValueError(
                    "One trajectory hash has multiple scenario names: "
                    f"{record['name']!r} and {scenario.name!r}."
                )
            record["suites"].append(suite)

    for record in by_hash.values():
        record["suites"] = sorted(set(record["suites"]))
    return sorted(
        by_hash.values(),
        key=lambda item: (item["family"], item["name"]),
    )


def _render_suite_table() -> list[str]:
    lines = [
        "| Experiment suite | Scenario collection | Trajectories |",
        "|---|---|---:|",
    ]
    for suite in run_experiments.SUITES:
        if suite == "boundary":
            continue
        count = len(run_experiments.suite_scenarios(suite))
        lines.append(
            f"| `{suite}` | `{SUITE_GENERATORS[suite]}` | {count} |"
        )
    return lines


def render_markdown(entries: list[dict[str, Any]]) -> str:
    """Render the catalog as a reviewable, generated Markdown document."""
    source_counts = Counter(str(entry["source_kind"]) for entry in entries)
    lines = [
        "<!-- Generated by trajectory_catalog.py; do not edit manually. -->",
        "# Final Report Target Trajectories",
        "",
        "This catalog lists the exact trajectory generators used by the final-report "
        "experiment suites. Procedural trajectories are regenerated in memory and are "
        "not stored as standalone NPZ files. Only the two targets derived from recorded "
        "commands are retained under `inputs/`.",
        "",
        "Regenerate and validate this document with:",
        "",
        "```bash",
        "uv run --project exp/src --frozen python exp/src/trajectory_catalog.py \\",
        "  --check-report --output exp/src/TRAJECTORIES.md",
        "```",
        "",
        "## Experiment Suite Entry Points",
        "",
        *_render_suite_table(),
        "",
        "`boundary` is omitted because it contains 378 static joint-limit conditions, "
        "not Cartesian target trajectories.",
        "",
        "## Unique Trajectories",
        "",
        f"The dynamic suites reference {len(entries)} unique sampled targets: "
        f"{source_counts['procedural']} procedural, "
        f"{source_counts['frozen input']} frozen inputs, and "
        f"{source_counts['derived frozen']} time-compressed frozen derivative.",
        "",
        "Names encode the relevant generator parameters: `v` is linear speed in m/s, "
        "`w` is angular speed in rad/s, and `p`/`m` encode positive/negative decimal "
        "values. Exact parameter grids are defined by the suite entry points above.",
        "",
        "| # | Scenario | Family | Mode | Samples | Source | Builder | Used by suites | SHA-256 |",
        "|---:|---|---|---|---:|---|---|---|---|",
    ]
    for index, entry in enumerate(entries, start=1):
        suites = ", ".join(f"`{suite}`" for suite in entry["suites"])
        lines.append(
            f"| {index} | `{entry['name']}` | `{entry['family']}` | "
            f"`{entry['mode']}` | {entry['sample_count']} | "
            f"{entry['source_kind']} | `{entry['builder']}` | {suites} | "
            f"`{str(entry['trajectory_sha256'])[:12]}...` |"
        )
    lines.extend(
        [
            "",
            "The complete hashes and sampled scenario metadata are also recorded in "
            "`exp/manifests/<suite>/metadata.json`. Result traces may embed the target "
            "samples beside command, driver, and simulated state arrays; those copies "
            "are outputs, not additional trajectory definitions.",
            "",
        ]
    )
    return "\n".join(lines)


def validate_against_report(entries: list[dict[str, Any]]) -> list[str]:
    """Compare regenerated scenarios with the published suite manifests."""
    errors: list[str] = []
    for suite in run_experiments.SUITES:
        if suite == "boundary":
            continue
        manifest_path = REPORT_MANIFESTS / suite / "metadata.json"
        if not manifest_path.exists():
            errors.append(f"Missing report manifest: {manifest_path}")
            continue
        recorded = json.loads(manifest_path.read_text(encoding="utf-8"))
        recorded_hashes = {
            str(item["trajectory_sha256"])
            for item in recorded.get("scenarios", [])
        }
        generated_hashes = {
            str(study._scenario_metadata(scenario)["trajectory_sha256"])
            for scenario in run_experiments.suite_scenarios(suite)
        }
        if generated_hashes != recorded_hashes:
            errors.append(
                f"{suite}: generated trajectory hashes differ from report manifest"
            )

    top_manifest = json.loads(
        (REPORT_MANIFESTS / "manifest.json").read_text(encoding="utf-8")
    )
    expected_count = int(top_manifest["unique_target_trajectory_hashes"])
    if len(entries) != expected_count:
        errors.append(
            f"Catalog contains {len(entries)} trajectories; report records "
            f"{expected_count}."
        )
    return errors


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--format",
        choices=("markdown", "json"),
        default="markdown",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Write the catalog to this path instead of stdout.",
    )
    parser.add_argument(
        "--check-report",
        action="store_true",
        help="Verify generated trajectory hashes against exp/manifests.",
    )
    args = parser.parse_args()

    entries = build_catalog()
    if args.check_report:
        errors = validate_against_report(entries)
        if errors:
            raise SystemExit("\n".join(errors))

    if args.format == "json":
        rendered = json.dumps(entries, indent=2)
    else:
        rendered = render_markdown(entries)
    if args.output is None:
        print(rendered)
    else:
        args.output.write_text(rendered + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
